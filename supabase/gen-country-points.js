// gen-country-points.js — writes 020_country_points.sql from countries.js, so the
// server scores Dailies (daily_points in 021_scoring.sql) with exactly the same
// country centres the app uses.
//
// Re-run and re-apply whenever countries.js changes:
//   node supabase/gen-country-points.js

const fs   = require('fs');
const path = require('path');
const vm   = require('vm');

const root = path.join(__dirname, '..');
const ctx  = {};
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(root, 'countries.js'), 'utf8') + '\nthis.COUNTRIES = COUNTRIES;', ctx);

const rows = ctx.COUNTRIES.map(c => `  ('${c.name.replace(/'/g, "''")}', ${c.lat}, ${c.lon})`);

const sql = `-- 020_country_points.sql — GENERATED by gen-country-points.js, do not edit.
-- ${rows.length} country centres (the same ones countries.js uses), for scoring Dailies.
-- Run after 019_feedback.sql, then run 021_scoring.sql. Safe to re-run.

create table if not exists public.country_points (
  country text primary key,
  lat     double precision not null,
  lon     double precision not null
);
alter table public.country_points enable row level security;   -- read only by security definer functions

insert into public.country_points (country, lat, lon) values
${rows.join(',\n')}
on conflict (country) do update set lat = excluded.lat, lon = excluded.lon;
`;

fs.writeFileSync(path.join(__dirname, '020_country_points.sql'), sql);
console.log(`Wrote 020_country_points.sql (${rows.length} countries)`);
