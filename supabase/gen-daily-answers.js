// gen-daily-answers.js — writes 003_daily_answers.sql from the game's own
// Daily pick (store.js dailyIndex over countries.js), so the server validates
// against exactly what players see.
//
// Re-run and re-apply whenever countries.js changes order or contents:
//   node supabase/gen-daily-answers.js

const fs   = require('fs');
const path = require('path');
const vm   = require('vm');

const root = path.join(__dirname, '..');
const ctx  = { window: {}, localStorage: null };
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(root, 'countries.js'), 'utf8') + '\nthis.COUNTRIES = COUNTRIES;', ctx);
vm.runInContext(fs.readFileSync(path.join(root, 'store.js'), 'utf8') + '\nthis.dailyIndex = dailyIndex; this.DAILY_EPOCH = DAILY_EPOCH;', ctx);

const FROM = new Date(ctx.DAILY_EPOCH + 'T00:00:00Z');
const DAYS = 365 * 4;

const rows = [];
for (let i = 0; i < DAYS; i++) {
  const day  = new Date(FROM.getTime() + i * 86400000).toISOString().slice(0, 10);
  const name = ctx.COUNTRIES[ctx.dailyIndex(day)].name.replace(/'/g, "''");
  rows.push(`  ('${day}', '${name}')`);
}

const sql = `-- 003_daily_answers.sql — GENERATED by gen-daily-answers.js, do not edit.
-- Daily answers from ${rows[0].slice(4, 14)} for ${DAYS} days. Safe to re-run.

insert into public.daily_answers (day, country) values
${rows.join(',\n')}
on conflict (day) do update set country = excluded.country;
`;

fs.writeFileSync(path.join(__dirname, '003_daily_answers.sql'), sql);
console.log(`Wrote ${DAYS} days to 003_daily_answers.sql`);
