// gen-country-continents.js — writes 012_country_continents.sql from the game's
// own data (countries.js + COUNTRY_CONTINENT in country-facts.js), so themed room
// challenges pick from exactly the countries players can guess.
//
// Re-run and re-apply whenever countries.js changes:
//   node supabase/gen-country-continents.js

const fs   = require('fs');
const path = require('path');
const vm   = require('vm');

const root = path.join(__dirname, '..');
const ctx  = {};
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(root, 'countries.js'), 'utf8') + '\nthis.COUNTRIES = COUNTRIES;', ctx);
vm.runInContext(fs.readFileSync(path.join(root, 'country-facts.js'), 'utf8') + '\nthis.COUNTRY_CONTINENT = COUNTRY_CONTINENT;', ctx);

const rows = ctx.COUNTRIES.map(c => {
  const continent = ctx.COUNTRY_CONTINENT[c.code];
  if (!continent) throw new Error(`No continent for ${c.name} (${c.code})`);
  return `  ('${c.name.replace(/'/g, "''")}', '${continent}')`;
});

const sql = `-- 012_country_continents.sql — GENERATED by gen-country-continents.js, do not edit.
-- ${rows.length} countries by continent, for themed room challenges. Run after 011_rooms_hub.sql. Safe to re-run.

insert into public.country_continents (country, continent) values
${rows.join(',\n')}
on conflict (country) do update set continent = excluded.continent;
`;

fs.writeFileSync(path.join(__dirname, '012_country_continents.sql'), sql);
console.log(`Wrote 012_country_continents.sql (${rows.length} countries)`);
